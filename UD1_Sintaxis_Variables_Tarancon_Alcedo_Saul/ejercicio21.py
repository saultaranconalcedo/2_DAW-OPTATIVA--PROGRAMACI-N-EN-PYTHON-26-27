resultado1 = 5 + 3 * 2
resultado2 = (5 + 3) * 2
resultado3 = 20 / 4 + 3
resultado4 = 20 / (4 + 1)
resultado5 = 2 ** 3 * 4
resultado6 = 2 ** (3 * 2)

print("5 + 3 * 2 =", resultado1)
print("(5 + 3) * 2 =", resultado2)
print("20 / 4 + 3 =", resultado3)
print("20 / (4 + 1) =", resultado4)
print("2 ** 3 * 4 =", resultado5)
print("2 ** (3 * 2) =", resultado6)
print("Los parentesis agrupan operaciones y hacen que se calculen antes que las operaciones externas.")

